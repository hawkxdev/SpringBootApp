CREATE TABLE person (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    year_of_birth VARCHAR(4) NOT NULL
);

CREATE TABLE book (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    author VARCHAR(255) NOT NULL,
    published_year VARCHAR(4) NOT NULL,
    booking_time TIMESTAMP,
    person_id INTEGER REFERENCES person(id) ON DELETE RESTRICT,
    CONSTRAINT book_checkout_state CHECK (
        (person_id IS NULL AND booking_time IS NULL)
        OR (person_id IS NOT NULL AND booking_time IS NOT NULL)
    )
);

CREATE INDEX book_person_id_idx ON book(person_id);
